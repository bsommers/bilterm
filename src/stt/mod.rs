/// Supported local AI STT backend kinds (`STT-01`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum SttBackendKind {
    OpenAiCompatible,
    Ollama,
    LocalCli,
    Mock,
}

impl SttBackendKind {
    pub fn as_str(&self) -> &'static str {
        match self {
            Self::OpenAiCompatible => "openai_compatible",
            Self::Ollama => "ollama",
            Self::LocalCli => "local_cli",
            Self::Mock => "mock",
        }
    }
}

/// Operations dispatched through `Action::Voice(VoiceOp)` (`ARCH-R01`, `STT-03`).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum VoiceOp {
    /// Toggles voice recording on/off on the focused pane.
    Toggle,
    /// Starts voice recording targeting the focused (or specified) pane.
    Start { pane_id: Option<usize> },
    /// Stops voice recording and triggers transcription.
    Stop,
    /// Aborts voice recording and discards audio without transcribing.
    Cancel,
    /// Queries current STT status.
    Status,
    /// Switches the active STT provider kind.
    SetProvider { provider: SttBackendKind },
    /// Stages or submits a transcribed text segment into the target pane.
    ApplyTranscript {
        pane_id: Option<usize>,
        text: String,
        is_final: bool,
    },
    /// Updates live recording telemetry (RMS level & elapsed ms) for UI rendering.
    UpdateTelemetry {
        recording: bool,
        transcribing: bool,
        rms_db: i32,
        elapsed_ms: u64,
        error: Option<String>,
    },
    /// Directly injects a WAV buffer into the STT pipeline.
    InjectWav {
        pane_id: Option<usize>,
        wav_bytes: Vec<u8>,
    },
}

/// Snapshot of the STT subsystem state exposed to UI renderers and JSON-RPC (`ARCH-R02`).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SttUiStatus {
    pub enabled: bool,
    pub recording: bool,
    pub transcribing: bool,
    pub target_pane_id: Option<usize>,
    pub rms_db: i32,
    pub elapsed_ms: u64,
    pub last_transcript: Option<String>,
    pub last_error: Option<String>,
    pub active_provider: SttBackendKind,
}

impl Default for SttUiStatus {
    fn default() -> Self {
        Self {
            enabled: false,
            recording: false,
            transcribing: false,
            target_pane_id: None,
            rms_db: -96,
            elapsed_ms: 0,
            last_transcript: None,
            last_error: None,
            active_provider: SttBackendKind::OpenAiCompatible,
        }
    }
}

/// Asynchronous events emitted by the background `SttWorker` toward the UI loop.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SttEvent {
    /// Live recording activity and level telemetry for the OIA status bar.
    Telemetry {
        recording: bool,
        transcribing: bool,
        rms_db: i32,
        elapsed_ms: u64,
        error: Option<String>,
    },
    /// Transcription text generated by an STT provider.
    Transcript {
        pane_id: Option<usize>,
        text: String,
        is_final: bool,
    },
    /// Error message.
    Error(String),
}

/// Audio payload and metadata dispatched to an `SttProvider`.
#[derive(Debug, Clone)]
pub struct TranscriptionRequest {
    pub wav_bytes: Vec<u8>,
    pub model: String,
    pub language: Option<String>,
    pub vocabulary_prompt: Option<String>,
}

/// Response returned by an `SttProvider`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct TranscriptionResponse {
    pub text: String,
    pub provider: SttBackendKind,
    pub duration_ms: u64,
}
