//! The agent-facing control guide: one embedded text served everywhere (`AGUIDE-01`).
//!
//! `docs/agent-guide.md` is the single source. It is embedded here and reaches agents through
//! `bilterm agents-md` (stdout, no daemon needed), `bilterm agents-md --install [PATH]` (a
//! delimited block in a project's `AGENTS.md` / `CLAUDE.md`), the MCP `initialize` `instructions`
//! field plus the `bilterm://agents-md` resource, the `agent.guide` RPC and the in-app
//! `:agent guide` injection (`crate::wm::agent_guide`).

use std::fs;
use std::io;
use std::path::{Path, PathBuf};

/// The full guide (`docs/agent-guide.md`).
pub const GUIDE: &str = include_str!("../docs/agent-guide.md");

/// MCP resource URI of the guide.
pub const RESOURCE_URI: &str = "bilterm://agents-md";

/// Short `instructions` text for the MCP `initialize` result: a pointer plus the key rules.
pub const MCP_INSTRUCTIONS: &str = "Bilterm terminal multiplexer control plane. Read the resource \
bilterm://agents-md (same text: `bilterm agents-md`, RPC agent.guide) before driving panes. Key rules: \
inspect before acting (bilterm_workspace_status, bilterm_inspect_pane); run shell commands with \
bilterm_exec_command and confirm via command_blocks exit_code or events.poll, never blind sleeps; \
use bilterm_send_keys only for full-screen programs (alternate_screen); writes to echo_lock \
(password) or read_only panes are refused and must not be worked around; prompt and wait on other \
agents with bilterm_agent_control (prompt, wait, last_turn) and bilterm_agent_mail; every \
workspace operation is a colon command via bilterm_colon_command (catalog: bilterm://commands); \
target a named daemon with --daemon-name NAME or BILTERM_DAEMON.";

/// First line of the installed block. Everything between the markers is owned by bilterm.
pub const BEGIN_MARKER: &str = "<!-- BILTERM:AGENTS-MD:BEGIN (generated by `bilterm agents-md --install`; edits inside this block are overwritten) -->";
/// Last line of the installed block.
pub const END_MARKER: &str = "<!-- BILTERM:AGENTS-MD:END -->";
/// Prefixes used to find an existing block whatever the text after them says.
const BEGIN_PREFIX: &str = "<!-- BILTERM:AGENTS-MD:BEGIN";
const END_PREFIX: &str = "<!-- BILTERM:AGENTS-MD:END";

/// File name of the guide copy written to the private runtime dir for `:agent guide`.
pub const GUIDE_FILE_NAME: &str = "agent-guide.md";
/// Default `--install` target.
pub const DEFAULT_INSTALL_PATH: &str = "AGENTS.md";

/// The delimited block `--install` writes (markers included, trailing newline).
pub fn install_block() -> String {
    format!("{BEGIN_MARKER}\n{}\n{END_MARKER}\n", GUIDE.trim_end())
}

/// Returns `existing` with the bilterm block added or refreshed. Text outside the markers is
/// kept byte for byte. `Err` when the markers are unbalanced or out of order (nothing is guessed).
pub fn merge_block(existing: &str) -> Result<String, String> {
    let begins: Vec<usize> = existing.match_indices(BEGIN_PREFIX).map(|(i, _)| i).collect();
    let ends: Vec<usize> = existing.match_indices(END_PREFIX).map(|(i, _)| i).collect();
    match (begins.as_slice(), ends.as_slice()) {
        ([], []) => {
            let mut out = existing.to_string();
            if !out.is_empty() {
                if !out.ends_with('\n') {
                    out.push('\n');
                }
                out.push('\n');
            }
            out.push_str(&install_block());
            Ok(out)
        }
        ([b], [e]) if b < e => {
            // The block ends with the END marker's line (its newline included when present).
            let after_end = existing[*e..].find('\n').map_or(existing.len(), |n| e + n + 1);
            let mut out = String::with_capacity(existing.len() + GUIDE.len());
            out.push_str(&existing[..*b]);
            out.push_str(&install_block());
            out.push_str(&existing[after_end..]);
            Ok(out)
        }
        _ => Err("found unbalanced or repeated BILTERM:AGENTS-MD markers; fix or remove them by hand, nothing was written".to_string()),
    }
}

/// What `--install` did to the target file.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum InstallOutcome {
    Created,
    Updated,
    Unchanged,
}

/// Adds or refreshes the block in `path` (created when missing). Idempotent.
pub fn install(path: &Path) -> Result<InstallOutcome, String> {
    let existing = match fs::read_to_string(path) {
        Ok(s) => Some(s),
        Err(e) if e.kind() == io::ErrorKind::NotFound => None,
        Err(e) => return Err(format!("cannot read {}: {e}", path.display())),
    };
    let merged = merge_block(existing.as_deref().unwrap_or(""))?;
    if existing.as_deref() == Some(merged.as_str()) {
        return Ok(InstallOutcome::Unchanged);
    }
    fs::write(path, merged.as_bytes()).map_err(|e| format!("cannot write {}: {e}", path.display()))?;
    Ok(if existing.is_some() { InstallOutcome::Updated } else { InstallOutcome::Created })
}

/// Writes the guide to `agent-guide.md` (`0600`) in the private runtime dir and returns its path.
pub fn write_guide_file() -> Result<PathBuf, String> {
    let dir = crate::secure_fs::private_runtime_dir().map_err(|e| format!("cannot resolve private runtime dir: {e}"))?;
    let path = dir.join(GUIDE_FILE_NAME);
    crate::secure_fs::write_private_file(&path, GUIDE.as_bytes()).map_err(|e| format!("cannot write {}: {e}", path.display()))?;
    Ok(path)
}

/// The one-line prompt injected into an agent pane: it points at the guide file.
pub fn pointer_line(path: &Path) -> String {
    format!(
        "Read {} for bilterm control instructions (how to drive this terminal multiplexer: panes, daemons, other agents). Follow them from now on.",
        path.display()
    )
}

/// Usage text of `bilterm agents-md`.
pub fn usage() -> String {
    "\
Usage:
  bilterm agents-md                    Print the agent control guide (Markdown) to stdout
  bilterm agents-md --install [PATH]   Add or refresh the guide as a delimited block in PATH
                                       (default ./AGENTS.md; e.g. CLAUDE.md). Text outside the
                                       BILTERM:AGENTS-MD markers is never changed; rerunning is a no-op.
No daemon is needed. Inside bilterm, `:agent guide [PANE|all|--print]` hands the guide to an agent pane."
        .to_string()
}

/// Runs `bilterm agents-md ARGS` (args after the subcommand word). Returns `(stdout text, exit code)`;
/// a non-zero code means the text is an error message for stderr.
pub fn run_cli(args: &[String]) -> (String, i32) {
    match args.first().map(String::as_str) {
        None => (GUIDE.to_string(), 0),
        Some("-h" | "--help" | "help") => (format!("{}\n", usage()), 0),
        Some("--install") if args.len() <= 2 => {
            let path = PathBuf::from(args.get(1).map_or(DEFAULT_INSTALL_PATH, String::as_str));
            match install(&path) {
                Ok(InstallOutcome::Created) => (format!("created {} with the bilterm agent guide\n", path.display()), 0),
                Ok(InstallOutcome::Updated) => (format!("updated the bilterm agent guide block in {}\n", path.display()), 0),
                Ok(InstallOutcome::Unchanged) => (format!("{} already has the current bilterm agent guide\n", path.display()), 0),
                Err(e) => (format!("bilterm agents-md: {e}\n"), 1),
            }
        }
        Some(other) => (format!("bilterm agents-md: unexpected argument '{other}'\n{}\n", usage()), 2),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn merge_appends_then_is_idempotent_and_keeps_outside_text() {
        let before = "# My project\n\nrules here";
        let once = merge_block(before).unwrap();
        assert!(once.starts_with("# My project\n\nrules here\n\n<!-- BILTERM:AGENTS-MD:BEGIN"));
        assert!(once.ends_with("<!-- BILTERM:AGENTS-MD:END -->\n"));
        assert_eq!(merge_block(&once).unwrap(), once);
        let edited = format!("{once}\n## After\ntail\n").replace("Pick an interface", "STALE TEXT");
        let again = merge_block(&edited).unwrap();
        assert!(again.starts_with("# My project\n\nrules here\n\n"));
        assert!(again.ends_with("<!-- BILTERM:AGENTS-MD:END -->\n\n## After\ntail\n"));
        assert!(!again.contains("STALE TEXT") && again.contains("Pick an interface"));
    }

    #[test]
    fn merge_into_empty_is_just_the_block_and_bad_markers_are_refused() {
        assert_eq!(merge_block("").unwrap(), install_block());
        assert!(merge_block("x\n<!-- BILTERM:AGENTS-MD:BEGIN -->\nno end\n").is_err());
        assert!(merge_block("<!-- BILTERM:AGENTS-MD:END -->\n<!-- BILTERM:AGENTS-MD:BEGIN -->\n").is_err());
        let twice = format!("{}{}", install_block(), install_block());
        assert!(merge_block(&twice).is_err());
    }

    #[test]
    fn cli_prints_guide_and_rejects_unknown_arguments() {
        assert_eq!(run_cli(&[]), (GUIDE.to_string(), 0));
        assert_eq!(run_cli(&["--bogus".to_string()]).1, 2);
        assert!(run_cli(&["--help".to_string()]).0.contains("--install"));
        assert!(!GUIDE.contains(BEGIN_PREFIX), "the guide must not contain its own markers");
        assert!(MCP_INSTRUCTIONS.contains(RESOURCE_URI));
    }
}
